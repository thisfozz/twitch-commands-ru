export default function handler(req, res) {
    res.setHeader('Content-Type', 'text/plain; charset=utf-8');
    res.setHeader('Cache-Control', 'no-store');

    const rawUser =
    typeof req.query.user === 'string'
        ? req.query.user.trim().replace(/\s+/g, ' ') : '';

    const user = Array.from(rawUser || 'Зритель')
    .slice(0, 30)
    .join('');

    const candidates = [];

    for (const opening of openings) {
        for (const middle of middles) {
            for (const ending of endings) {
                const story = `${opening} ${middle} ${ending}`
                    .replace(/\{user\}/g, () => user);

            if (Buffer.byteLength(story, 'utf8') <= 400) {
                candidates.push(story);
            }
        }
        }
    }

    if (candidates.length === 0) {
        return res.status(200).send(
            `${user} захотел приключений. Кот был против. Кот победил.`
        );
    }

    const index = Math.floor(Math.random() * candidates.length);

    return res.status(200).send(candidates[index]);
}